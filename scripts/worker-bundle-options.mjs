// esbuild options shared by every bundled worker, including the service worker that
// `vite build` bundles again with the static cache manifest (scripts/static-cache-build.ts).

// The bundled workers use only Web Crypto (globalThis.crypto.subtle) and have
// zero Node crypto imports, so they run on CF Workers with no compatibility
// flags and no runtime polyfill.
export const workerBundleOptions = {
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  bundle: true,
  minify: false,
  conditions: ['worker', 'browser', 'import', 'default'],
  // cloudflare:* 是运行时自带的内置模块（amsg 用 cloudflare:workers 的 DurableObject
  // 基类）。它们不在 node_modules 里，不标 external 的话 esbuild 会当成缺失依赖报错。
  //
  // jszip：worker 侧代码从不调用它，但 amsg 经 apiConfigNormalize → novelaiImage 这条
  // 静态 import 链间接拉到了 novelaiImage.ts 里一个浏览器专用的 `await import('jszip')`
  // （解析中转站回传的图片 zip 包，只在前端跑）。esbuild 仍会把这条动态 import 纳入依赖图，
  // 而 jszip 的 package.json "main" 字段在 platform:'neutral' 下无法解析，导致整个
  // worker 构建失败。标 external：worker 运行时永远不会真的执行到那行 import，留空壳即可。
  external: ['cloudflare:*', 'jszip'],
};

